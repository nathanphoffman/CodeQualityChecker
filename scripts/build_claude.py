"""Build each project's CLAUDE.md from reusable pieces. Writes into claude/projects/<name>/ only; never touches the real projects.

    uv run python scripts/build_claude.py            build every project in claude/projects.toml
    uv run python scripts/build_claude.py NAME ...   build only these

A project's CLAUDE.md is the pieces that apply, stuck together in this order:
  1. RULES.md, word for word under a "Code rules" heading   always
  2. claude/claude-md-pieces/<language>.md              for each language detected in the real project (rust, python, typescript ...)
  3. claude/claude-md-pieces/<framework>.md             for each framework detected (next, react, bevy ...)
  4. claude/projects/<name>/CLAUDE.project.md  the hand-written notes for just that project
Pieces that do not exist are skipped. Deploy the result with scripts/sync_claude.py.
"""
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from codequality.detect import detect  # noqa: E402

CLAUDE_DIR = REPO / "claude"
PIECES_DIR = CLAUDE_DIR / "claude-md-pieces"
RULES_FILE = REPO / "RULES.md"  # the rules the grader checks, used as they are so the two can never drift apart
GENERATED_MARK = "<!-- GENERATED by scripts/build_claude.py. Do not edit; change the pieces or CLAUDE.project.md instead. -->"


def piece_text(name: str) -> str | None:
    path = PIECES_DIR / f"{name}.md"
    return path.read_text().strip() if path.exists() else None


def build_one(name: str, project_path: Path) -> str:
    """Build one project. Returns a one-line result for the report."""
    out_dir = CLAUDE_DIR / "projects" / name
    out_file = out_dir / "CLAUDE.md"
    if out_file.exists() and not out_file.read_text().startswith(GENERATED_MARK):
        return "skipped: CLAUDE.md here is hand-written. Move it to CLAUDE.project.md and build again."
    found = detect(project_path)
    wanted = [*sorted(found.languages), *sorted(found.frameworks)]
    parts = ["# Code rules\n\n" + RULES_FILE.read_text().strip()]
    parts += [text for text in (piece_text(piece) for piece in wanted) if text]
    used = ["RULES.md"] + [piece for piece in wanted if piece_text(piece)]
    project_notes = out_dir / "CLAUDE.project.md"
    if project_notes.exists():
        parts.append(project_notes.read_text().strip())
        used.append("CLAUDE.project")
    out_dir.mkdir(parents=True, exist_ok=True)
    out_file.write_text(GENERATED_MARK + "\n\n" + "\n\n".join(parts) + "\n")
    return "built from " + ", ".join(used)


def main() -> int:
    config = tomllib.loads((CLAUDE_DIR / "projects.toml").read_text())["projects"]
    chosen = sys.argv[1:] or list(config)
    for name in chosen:
        if name not in config:
            print(f"{name}: not in projects.toml")
            continue
        path = Path(config[name]).expanduser()
        print(f"{name}: " + (build_one(name, path) if path.is_dir() else f"skipped: {path} does not exist"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
